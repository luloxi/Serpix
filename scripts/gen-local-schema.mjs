// Dumps the app-data DDL (tables, indexes, columns added by ALTER) into lib/e2e/schema.generated.ts.
// Run: node scripts/gen-local-schema.mjs
// Check: node scripts/gen-local-schema.mjs --check
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "migrations");
const outFile = join(root, "lib/e2e/schema.generated.ts");

/** App tables the in-memory client database mirrors. Integration tables stay on the server. */
export const LOCAL_DATA_TABLES = [
  "contacts",
  "projects",
  "tasks",
  "financial_accounts",
  "financial_transactions",
  "activities",
  "activity_contacts",
  "time_entries",
  "timer_state",
  "documents",
  "document_items",
  "document_time_entries",
  "receipts",
  "recurring_rules",
];

function applyMigrations(db) {
  for (const file of readdirSync(migrationsDir).filter((name) => name.endsWith(".sql")).sort()) {
    const sql = readFileSync(join(migrationsDir, file), "utf8");
    try {
      db.exec(sql);
    } catch {
      for (const part of sql.split(/;\s*\n/)) {
        const statement = part.trim();
        if (!statement) continue;
        try { db.exec(statement); } catch { /* skip only if this sqlite build cannot run it */ }
      }
    }
  }
}

export function dumpLocalSchema() {
  const db = new DatabaseSync(":memory:");
  applyMigrations(db);
  const placeholders = LOCAL_DATA_TABLES.map(() => "?").join(", ");
  const rows = db.prepare(
    `SELECT type, name, tbl_name, sql FROM sqlite_master
     WHERE sql IS NOT NULL AND type IN ('table', 'index') AND tbl_name IN (${placeholders})
     ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, tbl_name, name`,
  ).all(...LOCAL_DATA_TABLES);
  const seen = new Set(rows.filter((row) => row.type === "table").map((row) => row.tbl_name));
  for (const table of LOCAL_DATA_TABLES) {
    if (!seen.has(table)) throw new Error("migration dump is missing table " + table);
  }
  const statements = rows.map((row) => String(row.sql).trim().replace(/;\s*$/, ""));
  return { tables: LOCAL_DATA_TABLES, statements };
}

function render(dump) {
  const body = dump.statements.map((sql) => sql + ";").join("\n");
  const tables = dump.tables.map((name) => "  " + JSON.stringify(name) + ",").join("\n");
  return `// Generated by scripts/gen-local-schema.mjs. Do not edit.
// Tables, indexes, and columns added by ALTER for the in-memory client database.

export const LOCAL_DATA_TABLES = [
${tables}
] as const;

export const LOCAL_SCHEMA_SQL = ${JSON.stringify(body)};
`;
}

const check = process.argv.includes("--check");
const dump = dumpLocalSchema();
const next = render(dump);
if (check) {
  const current = readFileSync(outFile, "utf8");
  if (current !== next) {
    console.error("lib/e2e/schema.generated.ts is stale. Run: node scripts/gen-local-schema.mjs");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next);
  console.log("wrote " + outFile);
}
